let LANG = "tr";
try { LANG = localStorage.getItem("bw-lang") || "tr"; } catch { LANG = "tr"; }
if (LANG !== "tr" && LANG !== "en") LANG = "tr";

function t(key, vars, fallback) {
  let s = (I18N[LANG] && I18N[LANG][key]);
  if (s == null) s = (I18N.tr && I18N.tr[key]);
  if (s == null) s = (fallback != null ? fallback : key);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
}

function getLang() { return LANG; }

function setLang(lang) {
  if (lang !== "tr" && lang !== "en") return;
  LANG = lang;
  try { localStorage.setItem("bw-lang", lang); } catch {}
  // Cookie for backend error-message translation (endpoints read it unchanged).
  try { document.cookie = "lang=" + lang + "; path=/; max-age=31536000; SameSite=Lax"; } catch {}
  document.documentElement.lang = lang;
  applyStaticI18n();
  const sel = document.getElementById("lang-select");
  if (sel && sel.value !== lang) sel.value = lang;
  if (typeof window.onLangChange === "function") {
    try { window.onLangChange(); } catch (e) { /* no-op */ }
  }
}

